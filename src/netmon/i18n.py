LANGUAGES: tuple[tuple[str, str], ...] = (
    ("en", "English"),
    ("ar", "العربية"),
)
DEFAULT_LANGUAGE = "en"
_current = DEFAULT_LANGUAGE


def set_language(code: str | None) -> str:
    global _current
    _current = code if code in {c for c, _ in LANGUAGES} else DEFAULT_LANGUAGE
    return _current


def get_language() -> str:
    return _current


def is_rtl() -> bool:
    return _current == "ar"


